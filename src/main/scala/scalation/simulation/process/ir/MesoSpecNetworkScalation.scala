/** The `MesoScalationRoadNetwork` class contains the native ScalaTion
 *  components and route paths produced for a mesoscopic road network.
 *  @param sources     the translated vehicle sources
 *  @param junctions   the translated junctions
 *  @param links       the translated mesoscopic links
 *  @param sinks       the translated sinks
 *  @param routePaths  the ordered runtime links for each route identifier
 */
case class MesoScalationRoadNetwork (sources: Array [VSource],
                                     junctions: Array [Junction],
                                     links: Array [MesoVTransport],
                                     sinks: Array [Sink],
                                     routePaths: Map [String, Array [MesoVTransport]])


//::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
/** The `MesoSpecNetworkScalation` object translates an accepted mesoscopic
 *  network containing branches and merges into native ScalaTion components.
 *  This structural slice follows validated route movements while the native
 *  agenda and FIFO queues retain scheduling responsibility.
 */
object MesoSpecNetworkScalation:

    //::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
    /** Translate an accepted MesoSpec into a native mesoscopic road network.
     *  Run controls and screen coordinates remain executable-model concerns.
     *  @param spec        the accepted mesoscopic specification
     *  @param director    the ScalaTion process model that owns the components
     *  @param makeEntity  the vehicle factory receiving its selected route
     *  @param nStop       the number of vehicles generated by each source
     *  @param stream      the first random-number stream used by the sources
     *  @param nt          the number of junction recording intervals
     *  @param nodeXY      optional display coordinates indexed by node id
     */
    def network (spec: MesoSpec, director: Model,
                 makeEntity: MesoRoute => Vehicle, nStop: Int,
                 stream: Int = 0, nt: Int = 1,
                 nodeXY: Map [String, (Int, Int)] = Map.empty): MesoScalationRoadNetwork =

        spec.validate ()                                        // accept only a legal MesoSpec
        checkNetwork (spec)                                     // enforce the current translator boundary

        val nodeSpecs = spec.nodes.sortBy (_.id)                // deterministic component order
        val nodeIndex = nodeSpecs.zipWithIndex.map ((n, i) => n.id -> i).toMap

        def location (nodeId: String): (Int, Int) =
            nodeXY.getOrElse (nodeId, (100 + 160 * nodeIndex(nodeId), 300))
        end location

        val junctionSpecs = nodeSpecs.filter (_.kind == MicroNodeKind.Junction)
        val junctions = Array.ofDim [Junction] (junctionSpecs.length)
        cfor (0, junctions.length) { i =>
            val node = junctionSpecs(i)                         // semantic junction declaration
            junctions(i) = Junction (node.id, Sharp (0.0), location (node.id), nt, 1)
        }

        val sinkSpecs = nodeSpecs.filter (_.kind == MicroNodeKind.Sink)
        val sinks = Array.ofDim [Sink] (sinkSpecs.length)
        cfor (0, sinks.length) { i =>
            val node = sinkSpecs(i)                             // semantic sink declaration
            sinks(i) = Sink (node.id, location (node.id))
        }

        val routesBySource = spec.demand.routes.groupBy (_.source)
        val sourceSpecs = spec.demand.sources.sortBy (_.id)
        val sources = Array.ofDim [VSource] (sourceSpecs.length)
        cfor (0, sources.length) { i =>
            val source = sourceSpecs(i)                         // semantic source declaration
            val routes = routesBySource(source.node).sortBy (_.id)
            val probabilities = VectorD (routes.map (_.probability))
            val routeRV = Discrete (probabilities, stream = stream + sourceSpecs.length + i)
            val arrivalRV = MesoSpecScalation.arrivalVariate (source.arrival, stream + i)
            sources(i) = VSource (source.id, director,
                () => makeEntity (routes(routeRV.gen.toInt)), 0, nStop,
                arrivalRV, location (source.node))
        }

        val sourceComponents = sourceSpecs.indices.map (i =>
            sourceSpecs(i).node -> sources(i).asInstanceOf [Component]).toMap
        val junctionComponents = junctionSpecs.indices.map (i =>
            junctionSpecs(i).id -> junctions(i).asInstanceOf [Component]).toMap
        val sinkComponents = sinkSpecs.indices.map (i =>
            sinkSpecs(i).id -> sinks(i).asInstanceOf [Component]).toMap
        val components = sourceComponents ++ junctionComponents ++ sinkComponents

        val linkSpecs = spec.links.sortBy (_.id)                // deterministic link order
        val links = Array.ofDim [MesoVTransport] (linkSpecs.length)
        cfor (0, links.length) { i =>
            val link = linkSpecs(i)                             // semantic link declaration
            val speed = link.length / link.freeFlowTime         // preserve free-flow time
            links(i) = MesoVTransport (link.id, components(link.from), components(link.to),
                speed, link.capacity, storageCapacity = link.storageCapacity)
            links(i).length = link.length                       // preserve physical road length
        }

        val linkMap = linkSpecs.indices.map (i => linkSpecs(i).id -> links(i)).toMap
        val routePaths = spec.demand.routes.map (route =>
            route.id -> route.links.map (linkMap)).toMap        // derive paths from MesoSpec

        MesoScalationRoadNetwork (sources, junctions, links, sinks, routePaths)
    end network

    //::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
    /** Check limitations of the current network translator slice.
     *  A source node has one native VSource because it is also a link endpoint.
     *  @param spec  the legal mesoscopic specification
     */
    private def checkNetwork (spec: MesoSpec): Unit =
        val sourceNodes = spec.demand.sources.map (_.node)      // executable source endpoints
        if sourceNodes.distinct.length != sourceNodes.length then
            throw new UnsupportedOperationException (
                "MesoSpecNetworkScalation supports one demand source per source node")
    end checkNetwork

end MesoSpecNetworkScalation


//::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
/** The `MesoSpecNetworkScalationModel` class executes a translated mesoscopic
 *  network with route-conditioned branching and merging.
 *  @param spec       the accepted network MesoSpec
 *  @param nodeXY     display coordinates indexed by node id
 *  @param name       the name of the simulation model
 *  @param reps       the number of independent replications
 *  @param animating  whether to animate the model
 *  @param aniRatio   the ratio of simulation speed to animation speed
 *  @param nStop      the number of vehicles generated by each source
 *  @param stream     the first random-number stream used by the sources
 */
class MesoSpecNetworkScalationModel (spec: MesoSpec,
                                     nodeXY: Map [String, (Int, Int)] = Map.empty,
                                     name: String = "MesoSpecNetworkScalationModel",
                                     reps: Int = 1, animating: Boolean = true,
                                     aniRatio: Double = 500.0, val nStop: Int = 4,
                                     stream: Int = 0)
      extends Model (name, reps, animating, aniRatio):

    //--------------------------------------------------
    // Translate and Register Model Components

    val network = MesoSpecNetworkScalation.network (
        spec, this, route => Car (route.id), nStop, stream, nodeXY = nodeXY)

    cfor (0, network.sources.length) { i => addComponent (network.sources(i)) }
    cfor (0, network.junctions.length) { i => addComponent (network.junctions(i)) }
    cfor (0, network.sinks.length) { i => addComponent (network.sinks(i)) }
    cfor (0, network.links.length) { i => addComponent (network.links(i)) }

    //--------------------------------------------------
    // Specify the Vehicle Script

    case class Car (routeId: String) extends Vehicle ("c", this):

        override def act (): Unit =
            val path = network.routePaths(routeId)              // selected ordered route
            cfor (0, path.length) { i =>
                val link = path(i)                              // next mesoscopic link
                link.move ()
                link.to match
                    case junction: Junction => junction.jump ()
                    case sink: Sink          => sink.leave ()
                    case other => throw new IllegalStateException (
                        s"route '$routeId' reached unsupported component '$other'")
            }
        end act

    end Car

    simulate ()
    waitFinished ()

end MesoSpecNetworkScalationModel


//::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
/** The `runMesoSpecNetworkScalation` main function tests deterministic
 *  translation of two sources that merge, share a link and then branch to
 *  separate sinks.
 *  > runMain scalation.simulation.process.ir.runMesoSpecNetworkScalation
 */
@main def runMesoSpecNetworkScalation (): Unit =

    banner ("Branch/merge MesoSpec to ScalaTion test")

    val arrival = MicroArrival (MicroArrivalModel.Deterministic,
                                Array (MicroParameter ("x", 0.5)))
    val microNodes = Array (
        MicroNode ("west", MicroNodeKind.Source),
        MicroNode ("ramp", MicroNodeKind.Source),
        MicroNode ("merge", MicroNodeKind.Junction),
        MicroNode ("split", MicroNodeKind.Junction),
        MicroNode ("north", MicroNodeKind.Sink),
        MicroNode ("east", MicroNodeKind.Sink))
    val microSegments = Array (
        MicroSegment ("micro-west", "west", "merge", 200.0, 1, 10.0),
        MicroSegment ("micro-ramp", "ramp", "merge", 200.0, 1, 10.0),
        MicroSegment ("micro-trunk", "merge", "split", 300.0, 1, 10.0),
        MicroSegment ("micro-north", "split", "north", 200.0, 1, 10.0),
        MicroSegment ("micro-east", "split", "east", 200.0, 1, 10.0))
    val microSources = Array (
        MicroSource ("west-source", "west", arrival),
        MicroSource ("ramp-source", "ramp", arrival))
    val microRoutes = Array (
        MicroRoute ("west-north", "west", "north",
                    Array ("micro-west", "micro-trunk", "micro-north"), 1.0),
        MicroRoute ("ramp-east", "ramp", "east",
                    Array ("micro-ramp", "micro-trunk", "micro-east"), 1.0))
    val dynamics = MicroVehicleDynamics (
        CarFollowingModel.IDM,
        ODESolverType.Ballistic,
        Array (MicroParameter ("timeHeadway", 1.5),
               MicroParameter ("minimumGap", 2.0)),
        0.5)
    val micro = MicroIR (
        MicroIR.version,
        MicroNetwork (microNodes, microSegments),
        MicroDemand (microSources, microRoutes),
        dynamics,
        Array (MicroObservable (MicroMeasure.Flow, "micro-trunk"),
               MicroObservable (MicroMeasure.TravelTime, "west-north"),
               MicroObservable (MicroMeasure.TravelTime, "ramp-east")))

    val links = Array (
        MesoLink ("west-link", Array ("micro-west"), "west", "merge",
                  200.0, 20.0, 1800.0, 4),
        MesoLink ("ramp-link", Array ("micro-ramp"), "ramp", "merge",
                  200.0, 20.0, 1800.0, 4),
        MesoLink ("trunk-link", Array ("micro-trunk"), "merge", "split",
                  300.0, 30.0, 1800.0, 4),
        MesoLink ("north-link", Array ("micro-north"), "split", "north",
                  200.0, 20.0, 1800.0, 4),
        MesoLink ("east-link", Array ("micro-east"), "split", "east",
                  200.0, 20.0, 1800.0, 4))
    val movements = Array (
        MesoMovement ("west-merge", "merge", "west-link", "trunk-link",
                      Array ("west-north")),
        MesoMovement ("ramp-merge", "merge", "ramp-link", "trunk-link",
                      Array ("ramp-east")),
        MesoMovement ("north-turn", "split", "trunk-link", "north-link",
                      Array ("west-north")),
        MesoMovement ("east-turn", "split", "trunk-link", "east-link",
                      Array ("ramp-east")))
    val sources = Array (
        MesoSource ("west-source", "west", arrival),
        MesoSource ("ramp-source", "ramp", arrival))
    val routes = Array (
        MesoRoute ("west-north", "west", "north",
                   Array ("west-link", "trunk-link", "north-link"), 1.0),
        MesoRoute ("ramp-east", "ramp", "east",
                   Array ("ramp-link", "trunk-link", "east-link"), 1.0))
    val spec = MesoSpec (
        MesoSpec.version,
        micro.version,
        micro.sha256,
        Array (MesoNode ("west", MicroNodeKind.Source),
               MesoNode ("ramp", MicroNodeKind.Source),
               MesoNode ("merge", MicroNodeKind.Junction),
               MesoNode ("split", MicroNodeKind.Junction),
               MesoNode ("north", MicroNodeKind.Sink),
               MesoNode ("east", MicroNodeKind.Sink)),
        links,
        movements,
        MesoDemand (sources, routes),
        Array (MesoObservable (MicroMeasure.Flow, "trunk-link"),
               MesoObservable (MicroMeasure.TravelTime, "west-north"),
               MesoObservable (MicroMeasure.TravelTime, "ramp-east")),
        MesoSpec.eventOrder)

    val nodeXY = Map (
        "west" -> (100, 200), "ramp" -> (100, 400),
        "merge" -> (350, 300), "split" -> (600, 300),
        "north" -> (850, 200), "east" -> (850, 400))

    spec.validateAgainst (micro)                               // accept this abstraction
    val model = new MesoSpecNetworkScalationModel (spec, nodeXY)
    val linkMap = model.network.links.map (link => link.name -> link).toMap
    val sinkMap = model.network.sinks.map (sink => sink.name -> sink).toMap
    val junctionMap = model.network.junctions.map (j => j.name -> j).toMap
    val total = model.nStop * model.network.sources.length

    assert (linkMap("west-link").enteredCount == model.nStop)
    assert (linkMap("ramp-link").enteredCount == model.nStop)
    assert (linkMap("trunk-link").enteredCount == total)
    assert (linkMap("north-link").enteredCount == model.nStop)
    assert (linkMap("east-link").enteredCount == model.nStop)
    assert (sinkMap("north").durationStat.num == model.nStop)
    assert (sinkMap("east").durationStat.num == model.nStop)
    assert (junctionMap("merge").durationStat.num == total)
    assert (junctionMap("split").durationStat.num == total)
    cfor (0, model.network.links.length) { i =>
        val link = model.network.links(i)                       // translated link under test
        assert (link.enteredCount == link.releasedCount)
        assert (link.occupancy == 0)
        assert (link.blockedCount == 0)
        assert (link.persistentStat.max <= link.storageCapacity)
    }

    banner ("Branch/merge MesoSpec to ScalaTion test: PASS")
    println (s"mesospec_sha256 = ${spec.sha256}")
    println (s"links=${model.network.links.length}, " +
             s"junctions=${model.network.junctions.length}, completed=$total")
    Model.shutdown ()

end runMesoSpecNetworkScalation
